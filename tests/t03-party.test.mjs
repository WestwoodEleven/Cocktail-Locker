import { open, check } from "./harness.mjs";
export default async function () {
  const p = await open({ user: null });
  check("party planner available signed out", await p.isVisible("#party-btn"));
  await p.click("#party-btn"); await p.waitForTimeout(100);
  check("party link", (await p.evaluate("location.hash")) === "#party");
  await p.fill("#pp-search", "negro"); await p.waitForTimeout(300);
  const n = await p.evaluate("document.querySelectorAll('[data-addparty]').length");
  check("search finds both Negronis", n === 2, String(n));
  await p.click("[data-addparty='neg-1']"); await p.waitForTimeout(100);
  check("search box keeps focus after adding", (await p.evaluate("document.activeElement.id")) === "pp-search");
  await p.fill("#pp-search", "mule"); await p.waitForTimeout(300);
  await p.click("[data-addparty='mule']"); await p.waitForTimeout(100);
  await p.fill("#pp-guests", "12"); await p.dispatchEvent("#pp-guests", "change"); await p.waitForTimeout(100);
  const main = await p.text("#main");
  check("12 guests x 2 = 24 split across 2 drinks", main.includes("24 drinks in total, split across 2") && /12 drinks/.test(main), main.slice(0, 400));
  check("negroni batch: 12 oz gin", (await p.text(".party-drink")).includes("12 | oz | Gin"), await p.text(".party-drink"));
  check("ginger beer added at serving, not batched", main.includes("Add to each glass at serving: 4 oz Ginger beer"));
  const shop = await p.text("#shop");
  check("shopping list: gin bottles", /Gin \| 12 oz · 1 × 750 ml bottle/.test(shop), shop);
  check("shopping list: limes estimated", /Lime juice \| 6 oz · about 6 limes/.test(shop), shop);
  check("shopping list: ginger beer cans", /Ginger beer \| 48 oz · about 4 × 12 oz cans/.test(shop), shop);
  check("ice estimate", shop.includes("about 18 lb"));
  check("menu card lists drinks", (await p.text("#menu-card")).includes("Moscow Mule"));
  await p.click("[data-sv='mule'][data-d='1']"); await p.waitForTimeout(100);
  check("manual servings override", (await p.text(".party-drink:nth-of-type(2) .sv")) === "13");
  await p.evaluate("location.hash = '#party'"); await p.reload(); await p.waitForTimeout(1200);
  const q = p;
  check("plan is remembered on this device", (await q.text("#main")).includes("Moscow Mule"));
  await q.click("#party-close");
  await q.click("#list button[data-id='pk']");
  await q.click("#party-add"); await q.waitForTimeout(100);
  check("+ Party from a drink page", (await q.text("#party-add")).includes("In your party"));
  await q.setViewportSize({ width: 390, height: 844 });
  await q.click("#party-add"); await q.waitForTimeout(150);
  check("no sideways scroll on phone", (await q.evaluate("document.documentElement.scrollWidth")) <= 390);
  check("no errors", p.errors.length === 0, p.errors.join("; "));
  await q.close();
}
