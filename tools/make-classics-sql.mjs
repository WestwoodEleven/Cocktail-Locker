// Writes supabase/classics.sql from tools/classics-data.mjs.
import { writeFileSync } from "node:fs";
import { CLASSICS } from "./classics-data.mjs";
// Same as slugify in js/10-standard.js.
const slugify = v => String(v || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
  .replace(/&/g, " and ").replace(/^\s*the\s+/, "").replace(/\s+cocktail\s*$/, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60);
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const rows = CLASSICS.map(([name, type, base, method, glass, garnish, ings, about, aliases]) => {
  const data = { name, type, base, method, glass, garnish, classic: name, about, notes: "",
    ingredients: ings.map(([amount, unit, n]) => ({ amount, unit, name: n })) };
  const al = "array[" + aliases.map(a => q(slugify(a))).join(", ") + "]::text[]";
  return `  (${q(slugify(name))}, ${q(name)}, ${q(JSON.stringify(data))}::jsonb, ${al})`;
});
const sql = `-- My Cocktail Cart: load the classics into the shared standard library.
-- Paste into the Supabase SQL Editor and run once. Safe to run again: it never overwrites
-- a classic that's already there (so your corrections stay). Generated by tools/make-classics-sql.mjs.

-- Site admins can correct classics from the recipe page (⋯ More > Edit this classic).
drop policy if exists "Admins can edit standard recipes" on public.standard_recipes;
create policy "Admins can edit standard recipes" on public.standard_recipes for update to authenticated
  using (public.is_site_admin()) with check (public.is_site_admin());

insert into public.standard_recipes (slug, name, data, aliases) values
${rows.join(",\n")}
on conflict (slug) do nothing;
`;
writeFileSync(new URL("../supabase/classics.sql", import.meta.url), sql);
console.log("Wrote supabase/classics.sql with " + rows.length + " classics");
